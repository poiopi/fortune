// 複製元:zense.php 231-235行目 strHash()
// JSのMath.imul(31,h)+charCode|0という32bit符号付き整数演算を、PHPで正確に再現する。
//
// 【重要・仕様書からの変更点】仕様書ではord($str[$i])でバイト単位に処理する案が
// 示されていたが、これはUTF-8の日本語名（1文字=3バイト等）ではJSのcharCodeAt()
// （UTF-16コードユニット単位、BMP文字は1文字=1コード）と異なる値になってしまう
// バグがあるため、mb_str_split/mb_ordで文字単位のUnicodeコードポイントを取り、
// JSのcharCodeAt()と同じ値を得るように実装している（BMP外のサロゲートペア文字
// のみ稀に差異が出るが、日本語の氏名では実質的に発生しない）。
function zense_strHash(string $str): int {
    $h = 5381;
    $chars = mb_str_split($str, 1, 'UTF-8');
    foreach ($chars as $ch) {
        $code = mb_ord($ch, 'UTF-8');
        $h = (($h * 31 + $code) & 0xFFFFFFFF);
        if ($h >= 0x80000000) { $h -= 0x100000000; }
    }
    return abs($h);
}
// 複製元:zense.php 236-238行目 seededPick()
function zense_seededPick(array $arr, int $seed, string $salt): string {
    $idx = abs(zense_strHash((string)$seed . $salt)) % count($arr);
    return $arr[$idx];
}

