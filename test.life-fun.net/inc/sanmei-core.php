// 複製元：inc/oracle.php 36-41行目 myGregorianToJD() と同一の式
// （oracle.php自体はrequireしない、式のみ複製）
function sanmei_calcJDN(int $y, int $m, int $d): int {
    if ($m <= 2) { $y--; $m += 12; }
    $a = (int)($y / 100);
    $b = 2 - $a + (int)($a / 4);
    return (int)(365.25 * ($y + 4716)) + (int)(30.6001 * ($m + 1)) + $d + $b - 1524;
}

// 複製元：sanmei.php 331-335行目 getDayPillar()のstem算出部分
function sanmei_calcGmIdx(int $year, int $month, int $day): int {
    $jdn = sanmei_calcJDN($year, $month, $day);
    $cycle = ($jdn + 49) % 60;
    return $cycle % 10;
}

