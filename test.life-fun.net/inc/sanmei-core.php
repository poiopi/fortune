// 複製元:sanmei.php 324-329行目 getJDN()と同一の式
function sanmei_calcJDN(int $year, int $month, int $day): int {
    $a = (int) floor((14 - $month) / 12);
    $y = $year + 4800 - $a;
    $m = $month + 12 * $a - 3;
    return $day + (int)floor((153 * $m + 2) / 5) + 365 * $y +
        (int)floor($y / 4) - (int)floor($y / 100) + (int)floor($y / 400) - 32045;
}

// 複製元:sanmei.php 331-335行目 getDayPillar()のstem算出部分
function sanmei_calcGmIdx(int $year, int $month, int $day): int {
    $jdn = sanmei_calcJDN($year, $month, $day);
    $cycle = ($jdn + 49) % 60;
    return $cycle % 10;
}

