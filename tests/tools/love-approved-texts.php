function check(string $label, bool $ok, string $detail = ''): void {
    global $fail, $log;
    if (!$ok) $fail++;
    $log[] = sprintf("[%s] %s%s", $ok ? 'PASS' : 'FAIL', $label, $detail !== '' ? " — {$detail}" : '');
}

/** 先頭1件と残り件数だけを示す */
function firstFew(array $errs): string {
    return $errs ? ($errs[0] . (count($errs) > 1 ? ' (+' . (count($errs) - 1) . ' more)' : '')) : '';
}

$bank = LOVE_STYLE_TEXTS + LOVE_TENDENCY_TEXTS;

/** 承認済みの文（項目 => 段階 => 文）と文言バンクを1本ずつ比べ、違うものを列挙する */
function compareTexts(array $approved, array $bank): array {
    $errs = [];
    foreach ($approved as $item => $levels) {
        foreach ($levels as $lv => $text) {
            $actual = $bank[$item][$lv] ?? null;
            if ($actual !== $text) $errs[] = "{$item} {$lv}: 承認済み「{$text}」 / inc「" . ($actual ?? '(無し)') . '」';
        }
    }
    return $errs;
}

